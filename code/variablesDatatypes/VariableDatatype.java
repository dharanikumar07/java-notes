public class VariableDatatype {
    public static void main(String a[]) {
        int num = 1;
        float num2 = 1.1f;
        double num3 = 1.12f;
        byte num4 = 127;
        System.out.println(num);
        System.out.println(num2);
        System.out.println(num3);
        System.out.println(num4);
    }
}